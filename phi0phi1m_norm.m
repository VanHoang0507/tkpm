         49.858999608322432245];

normA = norm(A,inf);
nA = normA;
% sqrtnormA = sqrt(normA);
d = [1 2 3 4 5 6 7 8 10];
for i = 1:8
    if nA <= theta(i)
        m = d(i);
        [R0,R1] = phi01_pade(A,m);
        return
    end
end

